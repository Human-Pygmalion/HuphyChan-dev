#!/bin/bash
# 모터가 달린 라즈베리파이에 명령을 보낸다. **두 번 건너뛴다.**
#
# 2026-09-10. 파이(192.168.0.16)는 이 컴퓨터에서 바로 안 닿습니다 — 파이는 192.168.0.x 쪽에
# 있고 이 컴퓨터는 192.168.20.x 쪽입니다. 로봇 컴퓨터(10.8.0.14, 같은 기계의 다른 주소
# 192.168.0.13)는 **양쪽에 다 닿아서** 그리로 건너뜁니다.
#
#     이 컴퓨터 --(WireGuard)--> 로봇 10.8.0.14 --(같은 랜)--> 파이 192.168.0.16
#
# 명령은 base64 로 감싸서 보냅니다. 두 번 건너뛰면 따옴표가 두 번 벗겨져서, 안 그러면
# 인용부호가 든 명령이 조용히 다른 뜻이 됩니다.
#
#     ./pi_run.sh 'ls ~/System_ID'
#     echo '긴 명령' | ./pi_run.sh -
set -e
HOP=${PI_HOP:-syaro@10.8.0.14}
PI=${PI_HOST:-maido@192.168.0.16}
if [ "$1" = "-" ]; then CMD=$(cat); else CMD="$*"; fi
B64=$(printf '%s' "$CMD" | base64 -w0)
ssh -o BatchMode=yes "$HOP" "ssh -o BatchMode=yes $PI 'echo $B64 | base64 -d | bash -s'"
