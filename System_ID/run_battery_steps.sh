#!/bin/bash
# 2026-09-10. 사용자 지시: **"Step Input 을 다양한 각도로 더 많이 넣어서 실험해줘.
# 삼각파는 줄여도 되."**
#
# 왜 계단 크기를 훑는가
# ---------------------
# 계단 하나로는 세 값 중 무엇이 맞고 무엇이 틀렸는지 못 가릅니다. **크기를 바꾸면 지배하는
# 물리가 바뀌기 때문**에, 크기를 훑으면 세 값이 각각 따로 시험됩니다.
#
#   작은 계단 (1.5~3도)   마찰의 죽은구간 안. 여기서는 **마찰**만 보입니다.
#                         (잔류 오차 = 마찰 ÷ 세기 = RS04 0.519/20 = 1.49도)
#   중간 계단 (5~12도)    토크가 아직 상한에 안 닿음. 여기가 **선형 구간**이고,
#                         지나친 양과 상승 시간이 **관성**과 **점성**을 같이 드러냅니다.
#   큰 계단 (20~45도)     토크가 상한(8 뉴턴미터)에 붙어 버팁니다. 그러면 응답이
#                         **관성 하나로만** 정해집니다 — 가속도 = (상한 − 마찰) ÷ 관성.
#
# 즉 같은 세 값이 세 구간에서 **서로 다른 방식으로** 시험됩니다. 한 크기에서만 맞추면
# 우연히 맞을 수 있지만, 여덟 크기를 한 벌의 값으로 다 맞히면 우연이 아닙니다.
#
# 삼각파와 처프는 이번에 **다시 돌리지 않습니다.** 30도 자료가 이미 있고(태그 c),
# 사용자가 삼각파는 줄여도 된다고 하셨습니다. 비교 그림은 그 기존 자료를 씁니다.
#
# 안전
# ----
# * 경계는 **추종 오차**에 걸립니다. 대칭 계단은 뛰는 순간 오차가 크기의 2배가 되므로
#   경계를 2.4배로 잡습니다(45도 계단 → 110도). 진짜 폭주는 여전히 잡힙니다 — 토크 상한
#   8 뉴턴미터면 가속도가 103 라디안/s^2 이라 110도를 지나는 데 0.19초(표본 760개)입니다.
# * 회차마다 **힘을 끄고 38도 아래로 식힌 뒤** 시작합니다(--cool-to). 훑기는 회차가 많아
#   열이 쌓이는데, 온도 상한 47도에 걸려 중간에 끊기면 그 크기의 자료를 통째로 잃습니다.
set -e
cd "$(dirname "$0")"
M=${1:-4}; MODEL=${2:-RS04}; KP=${3:-20}; KD=${4:-1.0}; REP=${5:-10}

echo "===== 1부: 계단 크기 훑기 (자리는 0도 고정) ====="
for A in 1.5 3 5 8 12 20 30 45; do
  B=$(python3 -c "print(max(25.0, 2.4*$A))")
  echo "--- 계단 +-${A}도 (경계 ${B}도) ---"
  python3 -u pd_profiles.py step --motor-id $M --model $MODEL --kp $KP --kd $KD \
          --amp $A --period-s 1.5 --cycles 4 --repeats $REP \
          --bound-deg $B --cool-to 38 --tag s
done

echo "===== 2부: 같은 크기(10도)를 축의 서로 다른 자리에서 ====="
# 마찰이 자리에 따라 다른가(코깅·베어링 편심)를 봅니다. 다르다면 하나의 마찰값으로
# 모형을 만드는 것 자체가 틀린 것이 됩니다. 자리들이 서로 섞이지 않게 복귀 허용오차를
# 25도에서 6도로 좁혔습니다.
for H in -60 -30 0 30 60; do
  echo "--- 자리 ${H}도에서 계단 +-10도 ---"
  python3 -u pd_profiles.py step --motor-id $M --model $MODEL --kp $KP --kd $KD \
          --amp 10 --period-s 1.5 --cycles 4 --repeats 6 \
          --home-deg $H --home-tol 6 --bound-deg 30 --cool-to 38 --tag p
done
echo ALL_DONE
