#!/usr/bin/env python3
"""Add the D455 to the LegOnly AB MJCF: a body `d455_link` on base_link (mass 116 g, blue mesh) and a MuJoCo
camera `d455_depth` on it. Same pose as the URDF (read back from d455_overlay_report.json, written by build_d455.py).

Camera model: pinhole from the datasheet depth field of view (87 deg horizontal), 848 x 480 pixels.
MuJoCo takes the intrinsics as `sensorsize` + `focal` (the way mjlab's own i2rt YAM D405 camera does it):
pixel pitch p = 3 um (OV9782), sensorsize = (W p, H p), focal = (fx p, fy p) with fx = fy = (W/2)/tan(HFOV/2).
MuJoCo cameras look along -Z with +X right, +Y up; d455_link is ROS body (x forward, y left, z up), so the camera
frame is given by xyaxes = "0 -1 0  0 0 1" (right = -y, up = +z).

The shipped MJCF is NOT touched. Writes `<name>_d455_loop.xml`. The compiler `meshdir` stays `assets_v30_armfix/` (unchanged); the two new
meshes are reached through ONE extra symbolic link `xmls/assets_v30_d455 -> pygmalion_locomotion/assets/pygmalion_v2/meshes_d455`
(same style as the other `assets_*` links) with a path relative to meshdir (`../assets_v30_d455/...`).  usage (mjlab venv): build_d455_mjcf.py
"""
import json
import math
import os
import sys

import numpy as np

from lxml import etree

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import build_d455 as B  # noqa: E402

XMLS = f'{B.REPO}/mujoco-sim/mjlab/src/mjlab/asset_zoo/robots/pygmalion/xmls'
BASE = 'LegOnly_prototype-tempmass-motormeasured-armfix_v30_proxyfix_loop'
OUT = 'LegOnly_prototype-tempmass-motormeasured-armfix_v30_proxyfix_d455_loop'
MESHLINK = 'assets_v30_d455'
W, H, HFOV_DEG, PIXEL = 848, 480, 87.0, 3.0e-6


def f(v):
    return ' '.join(f'{x:.9g}' for x in v)


def main():
    rep = json.load(open(f'{B.ASSETS}/d455_overlay_report.json'))
    pos = rep['d455_link_in_base_link_m']
    pitch = rep['d455_mount_rpy_rad'][1]
    quat = (math.cos(pitch / 2), 0.0, math.sin(pitch / 2), 0.0)
    fx = (W / 2) / math.tan(math.radians(HFOV_DEG / 2))
    w, d, h = B.SIZE[1], B.SIZE[0], B.SIZE[2]
    diag = [B.MASS * (w * w + h * h) / 12, B.MASS * (d * d + h * h) / 12, B.MASS * (d * d + w * w) / 12]

    link = f'{XMLS}/{MESHLINK}'
    if os.path.islink(link):
        os.remove(link)
    os.symlink(f'{B.ASSETS}/meshes_d455', link)

    tree = etree.parse(f'{XMLS}/{BASE}.xml')
    root = tree.getroot()
    root.set('model', OUT)
    etree.SubElement(root.find('asset'), 'mesh', name='d455', file=f'../{MESHLINK}/d455.stl')
    etree.SubElement(root.find('asset'), 'mesh', name='pelvis_camera_mount', file=f'../{MESHLINK}/pelvis_camera_mount.stl')
    base = root.find(".//body[@name='base_link']")
    body = etree.SubElement(base, 'body', name='d455_link', pos=f(pos), quat=f(quat))
    etree.SubElement(body, 'inertial', pos=f(B.COM_IN_LINK), mass=str(B.MASS), diaginertia=f(diag))
    etree.SubElement(body, 'geom', {'class': 'visual', 'mesh': 'd455', 'rgba': '0.10 0.35 0.85 1'})
    etree.SubElement(body, 'camera', name='d455_depth', pos='0 0 0', xyaxes='0 -1 0 0 0 1',
                     resolution=f'{W} {H}', sensorsize=f'{W * PIXEL:.6g} {H * PIXEL:.6g}',
                     focal=f'{fx * PIXEL:.7g} {fx * PIXEL:.7g}')
    # the PLA mount bracket: a welded child of base_link (no joint), visual mesh only like the D455 (the base keeps its own contact geoms)
    mnt = rep['mount']
    mI = np.array(mnt['inertia_base_link_kg_m2'])
    mb = etree.SubElement(base, 'body', name='pelvis_camera_mount', pos='0 0 0')
    etree.SubElement(mb, 'inertial', pos=f(mnt['com_base_link_m']), mass=f"{mnt['mass_kg']:.9g}",
                     fullinertia=f([mI[0, 0], mI[1, 1], mI[2, 2], mI[0, 1], mI[0, 2], mI[1, 2]]))
    etree.SubElement(mb, 'geom', {'class': 'visual', 'mesh': 'pelvis_camera_mount', 'rgba': '0.86 0.86 0.80 1'})
    root.insert(0, etree.Comment(' D455 OVERLAY generated by tools/robot_model/camera_overlay/build_d455_mjcf.py '
                                 '(pose from d455_overlay_report.json). Do not hand-edit; rebuild. '))
    tree.write(f'{XMLS}/{OUT}.xml', encoding='utf-8', xml_declaration=False, pretty_print=True)
    print('wrote', f'{OUT}.xml', ' fx=fy=%.2f px' % fx)


if __name__ == '__main__':
    main()
